#!/usr/bin/env node
// PreToolUse (Edit|Write|MultiEdit|NotebookEdit): refuse hand edits to generated
// files and to Prisma migrations that are already applied somewhere.
//
// - packages/i18n/src/generated/keys.ts   -> regenerated from the catalog
// - docs/mobile-api-reference.html        -> pnpm docs:mobile-api
// - apps/api/prisma/migrations/<folder>/* -> denied once <folder> exists on
//   origin/development, origin/master or local development (deployed or
//   integrated). A new folder on a feature branch stays editable.
// - apps/api/prisma/migrations/migration_lock.toml -> always denied
//
// Fails open: if the input cannot be read, the call proceeds.

import { git, readHookInput, repoRelative, targetPath } from "./lib.mjs";

const GENERATED = {
  "packages/i18n/src/generated/keys.ts":
    "is generated from packages/i18n/src/catalog/tr.json. Edit the catalog instead; the PostToolUse hook (or `pnpm --filter @tarodan/i18n codegen`) regenerates it.",
  "docs/mobile-api-reference.html":
    "is generated by scripts/generate-mobile-api-doc.mjs. Change the generator and run `pnpm docs:mobile-api`.",
};
const MIGRATIONS = "apps/api/prisma/migrations/";
const APPLIED_REFS = ["origin/development", "origin/master", "development"];

export function denyReason(rel, folderExistsOn) {
  if (GENERATED[rel]) {
    return `${rel} ${GENERATED[rel]}`;
  }
  if (!rel.startsWith(MIGRATIONS)) {
    return undefined;
  }
  const rest = rel.slice(MIGRATIONS.length);
  if (rest === "migration_lock.toml") {
    return `${rel} is managed by Prisma; never edit it by hand.`;
  }
  const folder = rest.split("/")[0];
  if (!rest.includes("/")) {
    return undefined;
  }
  const ref = folderExistsOn(folder);
  if (ref) {
    return (
      `${MIGRATIONS}${folder} is already on ${ref}, so it is (or will be) applied by \`prisma migrate deploy\`. ` +
      "Never edit an applied migration: add a new migration folder that sorts after the latest one. See apps/api/prisma/CLAUDE.md."
    );
  }
  return undefined;
}

function main() {
  const input = readHookInput();
  const file = input && targetPath(input);
  const location = file && repoRelative(file);
  if (!location) {
    return;
  }
  const reason = denyReason(location.rel, (folder) =>
    APPLIED_REFS.find((ref) => {
      try {
        git(location.root, "cat-file", "-e", `${ref}:${MIGRATIONS}${folder}`);
        return true;
      } catch {
        return false;
      }
    }),
  );
  if (reason) {
    process.stdout.write(
      JSON.stringify({
        hookSpecificOutput: {
          hookEventName: "PreToolUse",
          permissionDecision: "deny",
          permissionDecisionReason: reason,
        },
      }),
    );
  }
}

main();
